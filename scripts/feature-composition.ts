import { dirname, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";

import type {
  DiscoveredFeature,
  FeatureAsset,
  FeatureModuleAsset,
} from "./feature-discovery";

export type RenderCompositionRegistryOptions = Readonly<{
  featuresDirectory: string | URL;
  outputFile: string | URL;
}>;

function filesystemPath(path: string | URL): string {
  return path instanceof URL ? fileURLToPath(path) : path;
}

function posixPath(path: string): string {
  return path.split(sep).join("/");
}

function importSpecifier(
  outputFile: string | URL,
  featuresDirectory: string | URL,
  assetPath: string,
): string {
  const absoluteAsset = resolve(filesystemPath(featuresDirectory), assetPath);
  let specifier = posixPath(
    relative(dirname(filesystemPath(outputFile)), absoluteAsset),
  );
  if (!specifier.startsWith(".")) specifier = `./${specifier}`;
  return specifier.replace(/\.tsx?$/, "");
}

function generatedHeader(owner: string): string[] {
  return [`/** Generated by ${owner}. Do not edit. */`, ""];
}

function sortedFeatures(
  features: readonly DiscoveredFeature[],
): DiscoveredFeature[] {
  return [...features].sort(({ descriptor: left }, { descriptor: right }) =>
    left.id < right.id ? -1 : left.id > right.id ? 1 : 0,
  );
}

function modules(
  assets: readonly FeatureAsset[],
  kind: FeatureModuleAsset["kind"],
): FeatureModuleAsset[] {
  return assets
    .filter(
      (asset): asset is FeatureModuleAsset =>
        asset.kind !== "message" && asset.kind === kind,
    )
    .sort(({ path: left }, { path: right }) =>
      left < right ? -1 : left > right ? 1 : 0,
    );
}

/** Client-safe feature metadata with no executable feature-module loaders. */
export function renderFeatureMetadataRegistry(
  features: readonly DiscoveredFeature[],
): string {
  const descriptors = sortedFeatures(features).map(({ descriptor }) => ({
    contributions: [...descriptor.contributions].sort(),
    dependencies: [...descriptor.dependencies].sort(),
    id: descriptor.id,
  }));
  return [
    ...generatedHeader("scripts/feature-composition.ts"),
    `export const features = ${JSON.stringify(descriptors, null, 2)} as const;`,
    "",
  ].join("\n");
}

/** Server-only lazy seed loaders; no browser-reachable registry imports this. */
export function renderSeedRegistry(
  assets: readonly FeatureAsset[],
  options: RenderCompositionRegistryOptions,
): string {
  const lines = [
    ...generatedHeader("scripts/feature-composition.ts"),
    'import "@tanstack/solid-start/server-only";',
    "",
    "export const featureSeeds = [",
  ];
  for (const asset of modules(assets, "seed")) {
    const specifier = importSpecifier(
      options.outputFile,
      options.featuresDirectory,
      asset.path,
    );
    lines.push(
      "  {",
      `    feature: ${JSON.stringify(asset.feature)},`,
      `    file: ${JSON.stringify(asset.path)},`,
      `    load: () => import(${JSON.stringify(specifier)}),`,
      "  },",
    );
  }
  lines.push("] as const;", "");
  return lines.join("\n");
}

/** Client-safe public/admin navigation imports and nothing else. */
export function renderNavigationRegistry(
  features: readonly DiscoveredFeature[],
  options: RenderCompositionRegistryOptions,
): string {
  const lines = generatedHeader("scripts/feature-composition.ts");
  const publicAliases: string[] = [];
  const adminAliases: string[] = [];

  for (const [index, { descriptor }] of sortedFeatures(features).entries()) {
    const hasPublic = descriptor.contributions.includes("navigation.public");
    const hasAdmin = descriptor.contributions.includes("navigation.admin");
    if (!hasPublic && !hasAdmin) continue;

    const imports: string[] = [];
    if (hasPublic) {
      const alias = `feature${index}PublicNavigation`;
      imports.push(`publicNavigation as ${alias}`);
      publicAliases.push(alias);
    }
    if (hasAdmin) {
      const alias = `feature${index}AdminNavigation`;
      imports.push(`adminNavigation as ${alias}`);
      adminAliases.push(alias);
    }
    const specifier = importSpecifier(
      options.outputFile,
      options.featuresDirectory,
      `${descriptor.id}/${descriptor.id}.navigation.tsx`,
    );
    lines.push(
      `import { ${imports.join(", ")} } from ${JSON.stringify(specifier)};`,
    );
  }

  if (publicAliases.length > 0 || adminAliases.length > 0) lines.push("");
  lines.push("export const publicNavigation = [");
  for (const alias of publicAliases) lines.push(`  ...${alias},`);
  lines.push("] as const;", "", "export const adminNavigation = [");
  for (const alias of adminAliases) lines.push(`  ...${alias},`);
  lines.push("] as const;", "");
  return lines.join("\n");
}

/** Client-safe profile-section imports selected by the explicit convention. */
export function renderProfileSectionRegistry(
  assets: readonly FeatureAsset[],
  options: RenderCompositionRegistryOptions,
): string {
  const lines = generatedHeader("scripts/feature-composition.ts");
  const aliases: string[] = [];

  for (const [index, asset] of modules(assets, "profileSection").entries()) {
    const alias = `feature${index}ProfileSections`;
    const specifier = importSpecifier(
      options.outputFile,
      options.featuresDirectory,
      asset.path,
    );
    lines.push(
      `import { profileSections as ${alias} } from ${JSON.stringify(specifier)};`,
    );
    aliases.push(alias);
  }

  if (aliases.length > 0) lines.push("");
  lines.push("export const profileSections = [");
  for (const alias of aliases) lines.push(`  ...${alias},`);
  lines.push("] as const;", "");
  return lines.join("\n");
}
