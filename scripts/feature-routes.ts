import { stat } from "node:fs/promises";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";

import {
  type DiscoveredFeature,
  writeGeneratedFile,
} from "./feature-discovery";

export type VirtualRouteFiles = Readonly<{
  admin: string;
  index: string;
  root: string;
}>;

export type RenderVirtualRoutesOptions = Readonly<{
  files?: VirtualRouteFiles;
}>;

export type WriteVirtualRoutesOptions = RenderVirtualRoutesOptions &
  Readonly<{
    features: readonly DiscoveredFeature[];
    featuresDirectory: string | URL;
    outputFile: string | URL;
  }>;

export const defaultVirtualRouteFiles: VirtualRouteFiles = {
  admin: "app/routes/admin.tsx",
  index: "app/routes/index.tsx",
  root: "app/routes/root.tsx",
};

function filesystemPath(path: string | URL): string {
  return path instanceof URL ? fileURLToPath(path) : path;
}

function contributingFeatures(
  features: readonly DiscoveredFeature[],
  contribution: "routes.admin" | "routes.public",
): string[] {
  return features
    .filter(({ descriptor }) => descriptor.contributions.includes(contribution))
    .map(({ descriptor }) => descriptor.id)
    .sort();
}

/**
 * Generates a TanStack virtual route tree for a router `routesDirectory` of
 * `src`. Public feature routes merge at `/`; admin routes merge below the
 * application-owned `/admin` shell.
 */
export function renderVirtualRoutesConfig(
  features: readonly DiscoveredFeature[],
  { files = defaultVirtualRouteFiles }: RenderVirtualRoutesOptions = {},
): string {
  const publicFeatures = contributingFeatures(features, "routes.public");
  const adminFeatures = contributingFeatures(features, "routes.admin");
  const lines = [
    "/** Generated by scripts/sync-features.ts. Do not edit. */",
    "",
    'import { index, physical, rootRoute, route } from "@tanstack/virtual-file-routes";',
    "",
    `export const routes = rootRoute(${JSON.stringify(files.root)}, [`,
    `  index(${JSON.stringify(files.index)}),`,
  ];

  for (const feature of publicFeatures) {
    lines.push(
      `  physical("", ${JSON.stringify(`feat/${feature}/routes/public`)}),`,
    );
  }

  lines.push(`  route("/admin", ${JSON.stringify(files.admin)}, [`);
  for (const feature of adminFeatures) {
    lines.push(
      `    physical("", ${JSON.stringify(`feat/${feature}/routes/admin`)}),`,
    );
  }
  lines.push("  ]),", "]);", "", "export default routes;", "");
  return lines.join("\n");
}

async function assertDirectory(
  path: string,
  contribution: string,
): Promise<void> {
  try {
    if ((await stat(path)).isDirectory()) return;
  } catch {
    // The contribution-specific error below is more useful than ENOENT.
  }
  throw new Error(`${contribution} requires route directory ${path}`);
}

/** Ensures route contributions cannot silently point at absent directories. */
export async function validateFeatureRouteDirectories(
  features: readonly DiscoveredFeature[],
  featuresDirectory: string | URL,
): Promise<void> {
  const directory = filesystemPath(featuresDirectory);
  for (const feature of features) {
    const { contributions, id } = feature.descriptor;
    if (contributions.includes("routes.public")) {
      await assertDirectory(
        resolve(directory, id, "routes/public"),
        `${id}:routes.public`,
      );
    }
    if (contributions.includes("routes.admin")) {
      await assertDirectory(
        resolve(directory, id, "routes/admin"),
        `${id}:routes.admin`,
      );
    }
  }
}

/** Validates physical mounts and writes the deterministic route config. */
export async function writeVirtualRoutesConfig({
  features,
  featuresDirectory,
  outputFile,
  files,
}: WriteVirtualRoutesOptions): Promise<string> {
  await validateFeatureRouteDirectories(features, featuresDirectory);
  const source = renderVirtualRoutesConfig(
    features,
    files === undefined ? {} : { files },
  );
  await writeGeneratedFile(outputFile, source);
  return source;
}
